export function translate(value: string, locale: string | null): string {
  if (!locale) return value;
  const parts = value.split(" / ");
  if (parts.length === 2 && /[А-Яа-яЁё]/.test(parts[0])) {
    const suffix =
      !parts[0].includes(": ") && parts[1].includes(": ")
        ? parts[1].slice(parts[1].indexOf(": "))
        : "";
    return locale === "en" ? parts[1] : parts[0] + suffix;
  }
  if (locale === "ru") return ru[value] ?? value;
  const reverse = Object.entries(ru).find(([, label]) => label === value)?.[0];
  if (!reverse && !Object.hasOwn(ru, value) && value !== "Сохранить")
    return value;
  if (/^[A-Z][A-Z_]+$/.test(value))
    return value
      .replaceAll("_", " ")
      .toLowerCase()
      .replace(/^./, (c) => c.toUpperCase());
  const english = reverse ?? value;
  return english === "Сохранить"
    ? "Save"
    : english
        .replace(/([a-z])([A-Z])/g, "$1 $2")
        .replace(/^([a-z])/, (c) => c.toUpperCase());
}
export function useTranslate() {
  const locale = useContext(Locale);
  return (value: string) => translate(value, locale);
}
export function LocaleText({ value }: { value: string }) {
  const t = useTranslate();
  return <>{t(value)}</>;
}
